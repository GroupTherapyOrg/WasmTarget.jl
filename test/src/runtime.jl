# WasmTarget's runtime (src/runtime/, the ports of dart's patch libraries, and src/julia/runtime/,
# Julia's own runtime raises): every closed world holds the runtime's roots (RUNTIME_ROOTS), and
# KernelNodes names each runtime method as dart2wasm's index.getProcedure names a patch member.

module RuntimeTest

using Test
using WasmTarget

const W = WasmTarget
const D = WasmTarget.Dart2Wasm

f(x::Int) = x + 1
g(x::Int) = x > 0 ? x : throw(DivideError())
h(x::Int, y::Int) = div(x, y)

names_of(world) = Set(b.ci.def.def.name for b in world)
@noinline pick_any(x::Int)::Union{Int,String} = x > 0 ? x : "neg"
checked_any(x::Int) = typeassert(pick_any(x), Int) + 1
world_of(p, at) = W.build_nir(W.check_subset(p, at, "runtime", Base.get_world_counter()), "runtime")

@testset "runtime: every closed world holds the runtime's roots, read from the ports' dart pragmas" begin
    # the roots: each Runtime port whose anchored dart declaration carries @pragma('wasm:entry-point'),
    # and Julia's own raisers, generated by dev/skeleton.jl (RUNTIME_ROOTS), each one method
    local roots = Set(last(r) for r in W.RUNTIME_ROOTS)
    @test issubset((:Error__throw_with_current_stack_trace, :StackTrace_current, :_TypeError__throw_as_check_error,
                    :throw_divide_error, :throw_bounds_error, :throw_undef_ref_error), roots)
    # Error._throw carries wasm:intrinsic, not wasm:entry-point: no root, reached through its caller
    @test !(:Error__throw in roots)
    # a program with no throw holds every root all the same, as dart's tree shaker roots each entry point
    # in every program, and it compiles as before
    local fw = world_of(f, (Int,))
    @test issubset(roots, names_of(fw)) && :Error__throw in names_of(fw)
    @test W.compile(f, (Int,); optimize = false)[1:4] == UInt8[0x00, 0x61, 0x73, 0x6d]
    # the program's bodies first: the roots are queued before the entry
    local gw = world_of(g, (Int,))
    @test first(gw).ci.def.def.name === :g && first(fw).ci.def.def.name === :f
    @test issubset((:h, :throw_divide_error), names_of(world_of(h, (Int, Int))))
    # a throw raises through errorThrowWithCurrentStackTrace's method, and a failed typeassert through
    # throwAsCheckError's: the compiled modules, run, raise what native Julia raises (the exception and
    # its fields, the runner's comparison)
    isdefined(Main, :WTChild) || Base.include(Main, joinpath(@__DIR__, "..", "run_child.jl"))
    local raising = [Main.WTChild.RunCase("g$(a)", W.compile(g, (Int,)), a, Main.WTChild.native_answer(g, a)) for a in [(2,), (-2,)]]
    append!(raising, [Main.WTChild.RunCase("checked_any$(a)", W.compile(checked_any, (Int,)), a, Main.WTChild.native_answer(checked_any, a)) for a in [(3,), (-1,)]])
    for r in Main.WTChild.run_cases(raising)
        @test r.ok || (@info r.label r.why; false)
    end
end

isdefined(Main, :WTChild) || Base.include(Main, joinpath(@__DIR__, "..", "run_child.jl"))

