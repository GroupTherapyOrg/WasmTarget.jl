# WasmTarget: a Julia → WebAssembly (WasmGC) compiler rebuilt from dart2wasm's structure
# (dev/MARCH.md Phase 1). src/ mirrors pkg/dart2wasm/lib and pkg/wasm_builder/lib/src at the commit
# dev/PARITY_MASTER.md pins, file for file, each file loaded by include_dart and each definition
# carrying @parity; src/julia/ holds what Julia forces and dart lacks, each definition carrying
# @quarantine (src/julia/parity.jl). This file defines nothing. Until a dart definition is ported,
# the path through it is a located rejection, never a value.
module WasmTarget

include("julia/parity.jl")
include("julia/construction.jl")
include("julia/reject.jl")
include("julia/subset.jl")
include("julia/nir.jl")
include("julia/classes.jl")
include("julia/kernel.jl")
include("julia/constant.jl")
include("julia/wasm_array.jl")
include("julia/entry.jl")
include("julia/late.jl")
include("julia/linked_hash_map.jl")
include("julia/collection.jl")
include("julia/union_find.jl")
include("julia/forward.jl")
include("julia/machine.jl")
include("julia/exports.jl")
include("julia/packages.jl")
include("julia/serializable.jl")

# the ports: every dart file of the pin table, each generated by dev/skeleton.jl and filled where a
# lane has ported it
include_dart(DART_FILES..., LLVM_FILES...)

# The load-time checks that need every definition to exist, so the package does not load otherwise:
# the file map, the anchors and the quarantine (src/julia/parity.jl), no abstract type that is
# neither a registered construction nor a dart abstract class's mirror (A33S1), every Union a
# @closed sum matched exhaustively, the strict subset's typestate (src/julia/subset.jl), the typed
# signatures and fields, and the anchors resolved at the pin.
construction_check(Val(:include_dart))
construction_check(Val(:parity))
construction_check(Val(:quarantine))
construction_check(Val(:check_no_open_abstract))
construction_check(Val(:AbstractModule))
construction_check(Val(:AbstractClosures))
construction_check(Val(:AbstractDispatchTable))
construction_check(Val(:AbstractModuleBuilder))
construction_check(Val(:AbstractInstructionsBuilder))
construction_check(Val(:closed))
construction_check(Val(:check_typed_signatures))
construction_check(Val(:check_typed_fields))
construction_check(Val(:ClosedWorld))
check_closed_world_makers()   # a stopgap read of lowered code (L224), run at load all the same
construction_check(Val(:NirValue))
construction_check(Val(:NirStmt))
construction_check(Val(:check_mirrors))
# every anchor resolves at the pin, where the pinned dart-lang/sdk checkout exists (L213)
_pin_sdk() === nothing || construction_check(Val(:check_anchors_resolve))
# Serializer.write takes every class dart's Serializable names, read at the pin (A42S5)
_pin_sdk() === nothing || construction_check(Val(:check_serializable_writable))
# dart2wasm's `w.` reaches only what wasm_builder.dart exports, composed through its directives
_pin_sdk() === nothing || construction_check(Val(:check_dart_exports))

end # module
