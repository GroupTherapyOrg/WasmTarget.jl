# Julia's Float16 conversions (julia/src/runtime_intrinsics.c), the routines LLVM's soft-promoted half calls
# (src/intrinsics.jl Val(:half)). Each is in a closed world where the program reaches it, never a root of every
# program: a statement of the closed world that is an intrinsic on a Float16 (an operand or its result one) reaches
# them (src/julia/subset.jl reached_runtime_ports), as a static link pulls a libcall's archive member only where
# the program's code references it, and as dart compiles a runtime member its program reaches (TFA).

# LLVM expands its FP16_TO_FP and FP_TO_FP16 into the libcalls __extendhfsf2 and
# __truncsfhf2, and Julia binds those names to its own runtime's (julia/src/jitlayers.cpp:1951 jl_crt,
# julia/src/aotcompile.cpp:1531 injectCRTAlias), the JL_DLLEXPORT julia__gnu_h2f_ieee and julia__gnu_f2h_ieee over
# the static half_to_float and float_to_half ported here word for word (C's int arithmetic on a uint32_t in
# UInt32's, wrapping as C's unsigned does). Julia's answer differs from compiler-rt's own __extendhfsf2
# (compiler-rt/lib/builtins/fp_extend_impl.inc) at a signalling NaN, which half_to_float quiets as the native
# host's conversion does; every other value converts alike. A double's truncation is not double_to_half's
# (runtime_intrinsics.c:190, which misrounds at a subnormal half's tie): src/intrinsics.jl rounds it to an f32
# inexact-to-odd first, as LLVM narrows in two steps

# runtime_intrinsics.c:18 half_to_float: a half's bits as the float of the same value, a NaN quieted
@quarantine pin"julia/src/runtime_intrinsics.c:18 half_to_float" "LLVM's soft-promoted half extends a half by the libcall __extendhfsf2, which Julia binds to its runtime's half_to_float (julia/src/jitlayers.cpp jl_crt); a wasm module has no libjulia, so its body is ported" Core.Float32 @noinline function julia_half_to_float(ival::UInt16)::Float32
    local sign = (UInt32(ival) & 0x8000) >> 15
    local exp = (UInt32(ival) & 0x7c00) >> 10
    local sig = (UInt32(ival) & 0x3ff) >> 0
    local ret::UInt32
    if exp == 0
        if sig == 0
            sign = sign << 31
            ret = sign | exp | sig
        else
            local n_bit = Int32(1)
            local bit = UInt16(0x0200)
            while (UInt32(bit) & sig) == 0
                n_bit = n_bit + Int32(1)
                bit = bit >> 1
            end
            sign = sign << 31
            exp = UInt32(Int32(-14) - n_bit + Int32(127)) << 23
            sig = ((sig & ~UInt32(bit)) << n_bit) << (23 - 10)
            ret = sign | exp | sig
        end
    elseif exp == 0x1f
        if sig == 0 # Inf
            ret = sign == 0 ? 0x7f800000 : 0xff800000
        else # NaN
            ret = 0x7fc00000 | (sign << 31) | (sig << (23 - 10))
        end
    else
        sign = sign << 31
        exp = (exp - UInt32(15) + UInt32(127)) << 23
        sig = sig << (23 - 10)
        ret = sign | exp | sig
    end
    return reinterpret(Float32, ret)
end

# runtime_intrinsics.c:159 float_to_half: van der Zijp's table conversion of a float to the nearest half, ties to
# even, a NaN quieted with its sign and its payload's upper bits
@quarantine pin"julia/src/runtime_intrinsics.c:159 float_to_half" "LLVM's soft-promoted half truncates a float by the libcall __truncsfhf2, which Julia binds to its runtime's float_to_half (julia/src/jitlayers.cpp jl_crt); a wasm module has no libjulia, so its body is ported" Core.UInt16 @noinline function julia_float_to_half(param::Float32)::UInt16
    local f = reinterpret(UInt32, param)
    if isnan(param)
        # Match the behaviour of arm64's fcvt or x86's vcvtps2ph by quieting
        # all NaNs (avoids creating infinities), preserving the sign, and using
        # the upper bits of the payload.
        #          sign                   exp      quiet    payload
        return (((f >> 16) & 0x8000) | 0x7c00 | 0x0200 | ((f >> 13) & 0x03ff)) % UInt16
    end
    local i = Int((f & ~UInt32(0x007fffff)) >> 23)
    local sh = Int(getindex(HALF_SHIFTTABLE, i + 1))
    f &= 0x007fffff
    # If `val` is subnormal, the tables are set up to force the
    # result to 0, so the significand has an implicit `1` in the
    # cases we care about.
    f |= UInt32(0x007fffff) + UInt32(0x1)
    local h = (UInt32(getindex(HALF_BASETABLE, i + 1)) + ((f >> sh) & 0x03ff)) % UInt16
    # round
    local nextbit = (f >> (sh - 1)) & 1
    if nextbit != 0 && (h & 0x7C00) != 0x7C00
        # Round halfway to even or check lower bits
        if (h & 0x0001) == 0x0001 || (f & ((UInt32(1) << (sh - 1)) - UInt32(1))) != 0
            h += UInt16(1)
        end
    end
    return h
end

